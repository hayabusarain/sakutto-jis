export interface CrossSectionGroup {
  /** 太さ d2 と許容差 */
  d2: number
  d2Tol: number
  /** D − d（溝の深さの2倍） */
  dDiff: number
  /** 溝幅 b（バックアップリング 0・1・2 個）。許容差は +0.25/0 */
  widths: readonly [number, number, number]
  /** 溝底の角の丸み R の最大値 */
  rMax: number
  /** E の最大値（寸法 K の最大値と最小値の差 = 同軸度の2倍。軸心のずれは E/2 まで） */
  eMax: number
  /** d・D の寸法許容差（d は 0/−、D は +/0）。未確認は null */
  diaTol: number | null
  /** 平面溝（固定用）: 深さ h（±0.05）・溝幅 b（+0.25/0） */
  flatDepth: number
  flatWidth: number
  /** 平面溝: 内圧用の溝外径 − 外圧用の溝内径 */
  flatOffset: number
}

